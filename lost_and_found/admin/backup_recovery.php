// 1. Handle Direct Download of Authorized Backup File
if (isset($_GET['action']) && $_GET['action'] === 'download') {
    $filename = basename($_GET['file'] ?? '');
    $filePath = $backupDir . '/' . $filename;

    if (empty($filename) || !file_exists($filePath) || substr($filename, -4) !== '.sql') {
        set_flash('error', 'Requested backup file is invalid or does not exist.');
        header('Location: ' . BASE_URL . '/admin/backup_recovery.php');
        exit;
    }

    log_activity('BACKUP_DOWNLOAD', 'backups', null, 'Downloaded backup archive: ' . $filename);
    header('Content-Description: File Transfer');
    header('Content-Type: application/sql');
    header('Content-Disposition: attachment; filename="' . $filename . '"');
    header('Expires: 0');
    header('Cache-Control: must-revalidate');
    header('Pragma: public');
    header('Content-Length: ' . filesize($filePath));
    readfile($filePath);
    exit;
}

// 2. Handle POST Backup Generation or Restoration
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    require_valid_csrf();
    $action = $_POST['action'] ?? '';

    // A. Generate Live SQL Backup
    if ($action === 'create_backup') {
        try {
            $timestamp = date('Y-m-d_H-i-s');
            $filename = 'lost_and_found_backup_' . $timestamp . '.sql';
            $targetPath = $backupDir . '/' . $filename;

            // Generate clean SQL dump of all tables
            $tables = ['users', 'categories', 'lost_items', 'found_items', 'item_matches', 'activity_logs', 'system_settings', 'backups'];
            
            $sqlDump = "-- ====================================================================\n";
            $sqlDump .= "-- Lost & Found Management System - Automated Database Backup\n";
            $sqlDump .= "-- Database: " . DB_NAME . "\n";
            $sqlDump .= "-- Generated By: " . $user['username'] . " (" . $user['full_name'] . ")\n";
            $sqlDump .= "-- Generated At: " . date('Y-m-d H:i:s') . "\n";
            $sqlDump .= "-- ====================================================================\n\n";
            $sqlDump .= "SET FOREIGN_KEY_CHECKS = 0;\nSET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';\nSTART TRANSACTION;\n\n";

            foreach ($tables as $table) {
                // Check if table exists
                $tableCheck = $db->query("SHOW TABLES LIKE '$table'")->fetch();
                if (!$tableCheck) continue;

                // 1. Table structure
                $createRow = $db->query("SHOW CREATE TABLE `$table`")->fetch(PDO::FETCH_NUM);
                $sqlDump .= "-- Table structure for `$table`\n";
                $sqlDump .= "DROP TABLE IF EXISTS `$table`;\n";
                $sqlDump .= $createRow[1] . ";\n\n";

                // 2. Table records
                $rows = $db->query("SELECT * FROM `$table`")->fetchAll(PDO::FETCH_ASSOC);
                if (!empty($rows)) {
                    $sqlDump .= "-- Dumping data for `$table`\n";
                    $columns = array_keys($rows[0]);
                    $colList = '`' . implode('`, `', $columns) . '`';

                    foreach ($rows as $row) {
                        $values = [];
                        foreach ($row as $val) {
                            if ($val === null) {
                                $values[] = 'NULL';
                            } else {
                                $values[] = $db->quote((string)$val);
                            }
                        }
                        $sqlDump .= "INSERT INTO `$table` ($colList) VALUES (" . implode(', ', $values) . ");\n";
                    }
                    $sqlDump .= "\n";
                }
            }

            $sqlDump .= "SET FOREIGN_KEY_CHECKS = 1;\nCOMMIT;\n-- End of Backup Dump\n";

            file_put_contents($targetPath, $sqlDump);
            $filesize = filesize($targetPath);

            // Record into backups table
            $stmt = $db->prepare(
                "INSERT INTO backups (filename, filesize, created_by_user_id, status, notes, created_at)
                 VALUES (:f, :s, :u, 'completed', 'Manual backup generated via administrator dashboard', NOW())"
            );
            $stmt->execute([
                'f' => $filename,
                's' => $filesize,
                'u' => $user['id']
            ]);
            $backupId = (int)$db->lastInsertId();

            log_activity('BACKUP_CREATED', 'backups', $backupId, "Created database backup: $filename ($filesize bytes)");
            set_flash('success', "Database backup '$filename' successfully generated (" . round($filesize / 1024, 2) . " KB).");
        } catch (Exception $e) {
            error_log('Backup creation failed: ' . $e->getMessage());
            set_flash('error', 'Backup failed: ' . $e->getMessage());
        }
        header('Location: ' . BASE_URL . '/admin/backup_recovery.php');
        exit;
    }

    // B. Restore From Server Backup File or Uploaded SQL
    if ($action === 'restore_backup') {
        $selectedFile = basename($_POST['selected_file'] ?? '');
        $filePath = null;

        // Check if an uploaded SQL file was provided
        if (!empty($_FILES['restore_upload']['name'])) {
            $tmpFile = $_FILES['restore_upload']['tmp_name'];
            $origName = $_FILES['restore_upload']['name'];

            if (substr(strtolower($origName), -4) !== '.sql') {
                set_flash('error', 'Restoration error: Only .sql files are supported.');
                header('Location: ' . BASE_URL . '/admin/backup_recovery.php');
                exit;
            }
            $filePath = $tmpFile;
        } elseif (!empty($selectedFile) && file_exists($backupDir . '/' . $selectedFile)) {
            $filePath = $backupDir . '/' . $selectedFile;
        }

        if (!$filePath || !file_exists($filePath)) {
            set_flash('error', 'No valid backup file selected for restoration.');
            header('Location: ' . BASE_URL . '/admin/backup_recovery.php');
            exit;
        }

        try {
            $sqlContent = file_get_contents($filePath);
            if (empty($sqlContent) || strlen($sqlContent) < 50) {
                throw new Exception('The selected backup file is empty or corrupted.');
            }

            // Execute SQL statements
            $db->exec("SET FOREIGN_KEY_CHECKS = 0;");
            $db->exec($sqlContent);
            $db->exec("SET FOREIGN_KEY_CHECKS = 1;");

            log_activity('DATABASE_RESTORED', 'system', null, 'Successfully restored database from ' . ($selectedFile ?: 'uploaded SQL file'));
            set_flash('success', 'Database successfully restored! All tables and records refreshed.');
        } catch (Exception $e) {
            error_log('Database restoration failed: ' . $e->getMessage());
            set_flash('error', 'Restoration failed: ' . $e->getMessage());
        }

        header('Location: ' . BASE_URL . '/admin/backup_recovery.php');
        exit;
    }
}

